let lang = 'en';
export const currentLang = () => lang;
export const setLang = l => { lang = MESSAGES[l] ? l : 'en'; };
// The language for a setting ('auto', 'en' or 'de') and the browser language: English unless German is chosen or the browser is German.
export const resolveLang = (setting, browser) => MESSAGES[setting] ? setting : /^de/i.test(browser || '') ? 'de' : 'en';

export function t(key, params = {}) {
  const raw = MESSAGES[lang][key] ?? MESSAGES.en[key] ?? key;
  return raw
    .replace(/\{(\w+):([^|{}]*)\|([^{}]*)\}/g, (m, k, one, other) => k in params ? (+params[k] === 1 ? one : other) : m)
    .replace(/\{(\w+)\}/g, (m, k) => k in params ? String(params[k]) : m);
}

// "1 sale", "2 sales": for the texts that are not in the tables above (log lines of the lib modules).
export const plural = (n, one, other = one + 's') => +n === 1 ? one : other;
export const count = (n, one, other) => `${n} ${plural(n, one, other)}`;

// 'PostNL cart', 'PostNL and DHL carts' or 'cart' for the display names of the carriers of a cart.
export function cartName(names) {
  return !names.length ? t('cart.name.none')
    : names.length === 1 ? t('cart.name.one', { a: names[0] })
    : t('cart.name.many', { list: names.slice(0, -1).join(', '), hlist: names.slice(0, -1).map(n => `${n}-`).join(', '), last: names[names.length - 1] });
}
// The parameters of a message that names carts: the name, and how many carts it names (1 when none, for German frames that inflect on it).
export const cartVars = names => ({ cart: cartName(names), carts: Math.max(1, names.length) });

// Fills the data-i18n attributes of a document or element.
export function applyI18n(root = document) {
  if (root.documentElement) root.documentElement.lang = lang;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const name of ['title', 'aria-label', 'placeholder'])
    for (const el of root.querySelectorAll(`[data-i18n-${name}]`)) el.setAttribute(name, t(el.getAttribute(`data-i18n-${name}`)));
}
